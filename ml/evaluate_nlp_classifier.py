"""Evaluate the trained drug-topic classifier on reviewed held-out messages.

No examples are generated by this script. The input must be a reviewed CSV
with the columns described in data/evaluation/README.md.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Tuple

import joblib
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATA = PROJECT_ROOT / "data" / "evaluation" / "hinglish_simulation_messages.csv"
DEFAULT_MODEL = PROJECT_ROOT / "models" / "registry" / "nlp_drug_topic.joblib"
REQUIRED_COLUMNS = {
    "message_id", "conversation_id", "channel", "language", "text", "drug_related_label"
}


def _read_data(path: Path) -> List[Dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames or not REQUIRED_COLUMNS.issubset(reader.fieldnames):
            raise ValueError(f"CSV must include columns: {', '.join(sorted(REQUIRED_COLUMNS))}")
        rows = []
        seen_ids = set()
        for row_number, row in enumerate(reader, start=2):
            if not any((value or "").strip() for value in row.values()):
                continue
            message_id = (row.get("message_id") or "").strip()
            text = (row.get("text") or "").strip()
            label_text = (row.get("drug_related_label") or "").strip()
            if not message_id or not text or label_text not in {"0", "1"}:
                raise ValueError(f"Invalid message_id, text, or binary label on CSV row {row_number}")
            if message_id in seen_ids:
                raise ValueError(f"Duplicate message_id on CSV row {row_number}: {message_id}")
            seen_ids.add(message_id)
            rows.append({**row, "message_id": message_id, "text": text,
                         "drug_related_label": label_text})
    if not rows:
        raise ValueError("No reviewed evaluation rows found; refusing to report metrics on an empty template")
    if {int(row["drug_related_label"]) for row in rows} != {0, 1}:
        raise ValueError("Evaluation data must include reviewed examples from both labels 0 and 1")
    return rows


def _evaluate(model: Any, rows: List[Dict[str, str]]) -> Dict[str, Any]:
    actual = [int(row["drug_related_label"]) for row in rows]
    predicted = [int(value) for value in model.predict([row["text"] for row in rows])]
    return {
        "rows": len(rows),
        "drug_related_positive_rows": sum(actual),
        "accuracy": float(accuracy_score(actual, predicted)),
        "balanced_accuracy": float(balanced_accuracy_score(actual, predicted)),
        "drug_related_precision": float(precision_score(actual, predicted, zero_division=0)),
        "drug_related_recall": float(recall_score(actual, predicted, zero_division=0)),
        "drug_related_f1": float(f1_score(actual, predicted, zero_division=0)),
        "confusion_matrix_labels_0_1": confusion_matrix(actual, predicted, labels=[0, 1]).tolist(),
        "classification_report": classification_report(
            actual, predicted, labels=[0, 1],
            target_names=["not_drug_related", "drug_related"],
            output_dict=True, zero_division=0,
        ),
    }


def evaluate(data_path: Path, model_path: Path) -> Dict[str, Any]:
    if not model_path.is_file():
        raise FileNotFoundError(f"Trained model not found: {model_path}")
    rows = _read_data(data_path)
    model = joblib.load(model_path)
    grouped: Dict[Tuple[str, str], List[Dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[((row.get("channel") or "unknown").strip().casefold(),
                 (row.get("language") or "unknown").strip().casefold())].append(row)
    return {
        "task": "drug_related_topic_classification",
        "data_file": data_path.name,
        "label_definition": "1=drug-related topic; 0=not labeled drug-related",
        "overall": _evaluate(model, rows),
        "by_channel_and_language": {
            f"{channel}:{language}": _evaluate(model, subset)
            for (channel, language), subset in sorted(grouped.items())
        },
        "limitations": [
            "Metrics only describe this reviewed evaluation file.",
            "This label does not measure suspicious dealing or trafficking.",
            "No model threshold was tuned or changed by this evaluator.",
        ],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    args = parser.parse_args()
    print(json.dumps(evaluate(args.data, args.model), indent=2))


if __name__ == "__main__":
    main()
